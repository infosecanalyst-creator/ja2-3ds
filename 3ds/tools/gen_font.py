#!/usr/bin/env python3
# Render anti-aliased DejaVu bitmap fonts into a C header for the 3DS UI.
import sys, json
from PIL import Image, ImageDraw, ImageFont
out = sys.argv[1]
F = "/usr/share/fonts/truetype/dejavu/"
specs = [("kFontSans", F + "DejaVuSans.ttf", 12), ("kFontBold", F + "DejaVuSans-Bold.ttf", 13),
         ("kFontMono", F + "DejaVuSansMono.ttf", 12), ("kFontBig", F + "DejaVuSans-Bold.ttf", 18)]
L = ["// Generated by tools/gen_font.py from DejaVu fonts. Do not edit.", "#pragma once",
     "struct N3DSGlyph { unsigned short off; unsigned char w, h; signed char x, y; unsigned char adv; };",
     "struct N3DSFont { int height, ascent; const N3DSGlyph* g; const unsigned char* a; };"]
metrics = {}
for name, path, size in specs:
    f = ImageFont.truetype(path, size)
    asc, desc = f.getmetrics()
    data = bytearray(); gl = []; adv = {}
    for c in range(32, 127):
        ch = chr(c); a = round(f.getlength(ch)); adv[ch] = a
        bb = f.getbbox(ch)
        if bb[2] <= bb[0] or bb[3] <= bb[1]:
            gl.append((len(data), 0, 0, 0, 0, a)); continue
        w, h = bb[2] - bb[0], bb[3] - bb[1]
        im = Image.new("L", (w, h), 0)
        ImageDraw.Draw(im).text((-bb[0], -bb[1]), ch, font=f, fill=255)
        gl.append((len(data), w, h, bb[0], bb[1], a)); data += bytes(im.getdata())
    metrics[name] = adv
    L.append("static const N3DSGlyph %s_g[95] = {%s};" % (name, ",".join("{%d,%d,%d,%d,%d,%d}" % g for g in gl)))
    L.append("static const unsigned char %s_a[%d] = {%s};" % (name, len(data), ",".join(map(str, data))))
    L.append("static const N3DSFont %s = { %d, %d, %s_g, %s_a };" % (name, asc + desc + 1, asc, name, name))
open(out, "w").write("\n".join(L) + "\n")
json.dump(metrics, open(out + ".metrics.json", "w"))
print("fonts written")
